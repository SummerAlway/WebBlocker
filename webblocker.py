    def install_extension(self) -> None:
        source = extension_source_dir()
        if source is None:
            messagebox.showerror(
                "找不到扩展文件",
                "程序目录中缺少 extension 文件夹，无法安装浏览器扩展。",
                parent=self.root,
            )
            return

        target = DATA_DIR / "extension"
        try:
            target.mkdir(parents=True, exist_ok=True)
            shutil.copytree(source, target, dirs_exist_ok=True)
        except OSError as exc:
            messagebox.showerror("复制失败", f"无法复制扩展文件：{exc}", parent=self.root)
            return

        self._log(f"浏览器扩展已释放到：{target}")
        try:
            if IS_WINDOWS:
                os.startfile(target)  # type: ignore[attr-defined]
            else:
                subprocess.Popen(["xdg-open", str(target)])
        except Exception:
            pass

        messagebox.showinfo(
            "安装浏览器扩展",
            "扩展文件夹已打开：\n{}\n\n"
            "Chrome / Edge 安装步骤：\n"
            "1. 地址栏打开 chrome://extensions（Edge 为 edge://extensions）；\n"
            "2. 打开右上角的“开发者模式”；\n"
            "3. 点“加载已解压的扩展程序”，选择上面的文件夹；\n"
            "4. 保持主程序运行，点扩展图标即可查看同步状态。\n\n"
            "修改网站列表后，扩展会在 30 秒内自动同步；\n"
            "也可以在扩展弹窗里点“立即同步”。".format(target),
            parent=self.root,
        )

