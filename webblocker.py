def extension_source_dir() -> Path | None:
    """找到 extension 文件夹（源码运行或 PyInstaller 打包后都能找到）。"""
    candidates: list[Path] = []
    if getattr(sys, "frozen", False):
        meipass = getattr(sys, "_MEIPASS", None)
        if meipass:
            candidates.append(Path(meipass) / "extension")
    candidates.append(Path(__file__).resolve().parent / "extension")

    for candidate in candidates:
        if (candidate / "manifest.json").is_file():
            return candidate
    return None


class RuleServer:
    """只监听 127.0.0.1，把主程序的网站列表提供给浏览器扩展。"""

    PORTS = range(8765, 8775)

    def __init__(self, payload_provider) -> None:
        self._provider = payload_provider
        self.httpd: ThreadingHTTPServer | None = None
        self.port: int | None = None
        self._thread: threading.Thread | None = None

    def start(self) -> int | None:
        provider = self._provider

        class Handler(BaseHTTPRequestHandler):
            def do_GET(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler 的约定
                path = urlparse(self.path).path
                if path == "/ping":
                    body = {"app": APP_NAME, "version": APP_VERSION}
                elif path == "/rules":
                    body = provider()
                else:
                    self.send_error(404)
                    return

                data = json.dumps(body, ensure_ascii=False).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "application/json; charset=utf-8")
                self.send_header("Content-Length", str(len(data)))
                self.send_header("Cache-Control", "no-store")
                origin = self.headers.get("Origin", "")
                if origin.startswith(("chrome-extension://", "moz-extension://")):
                    self.send_header("Access-Control-Allow-Origin", origin)
                self.end_headers()
                self.wfile.write(data)

            def log_message(self, *_args) -> None:  # 不在控制台刷访问日志
                pass

        for port in self.PORTS:
            try:
                httpd = ThreadingHTTPServer(("127.0.0.1", port), Handler)
            except OSError:
                continue

            httpd.daemon_threads = True
            self.httpd = httpd
            self.port = port
            self._thread = threading.Thread(
                target=httpd.serve_forever, name="webblocker-rules", daemon=True
            )
            self._thread.start()
            return port
        return None

    def stop(self) -> None:
        if self.httpd is None:
            return
        try:
            self.httpd.shutdown()
            self.httpd.server_close()
        except Exception:
            pass
        self.httpd = None
        self.port = None


