def ensure_admin(root: tk.Tk) -> bool:
    """返回 True 表示已具备管理员权限、可以继续启动。"""
    if is_admin() or not IS_WINDOWS:
        return True

    root.withdraw()
    answer = messagebox.askyesno(
        "需要管理员权限",
        "修改系统 hosts 文件需要管理员权限。\n\n是否以管理员身份重新启动？",
        parent=root,
    )
    if answer:
        if relaunch_as_admin():
            root.destroy()
            return False
        messagebox.showerror("启动失败", "无法获取管理员权限，程序即将退出。", parent=root)
    root.destroy()
    return False


def main() -> None:
    enable_dpi_awareness()
    root = tk.Tk()

    def report_callback_exception(exc_type, exc, _tb):  # noqa: ANN001
        messagebox.showerror("程序错误", f"{exc_type.__name__}: {exc}", parent=root)

    root.report_callback_exception = report_callback_exception

    if not ensure_admin(root):
        return

    root.deiconify()
    WebBlockerApp(root, load_config())
    root.mainloop()


if __name__ == "__main__":
    main()
