    # ---------------- 小工具 ----------------
    def _log(self, message: str) -> None:
        stamp = time.strftime("%H:%M:%S")
        self.log_box.configure(state="normal")
        self.log_box.insert("end", f"[{stamp}] {message}\n")
        self.log_box.see("end")
        self.log_box.configure(state="disabled")

    def _save(self) -> None:
        try:
            save_config(
                {"enabled": self.enabled, "browser": self.browser_enabled, "sites": self.sites}
            )
        except OSError as exc:
            self._log(f"保存设置失败：{exc}")

    def _rules_payload(self) -> dict:
        """扩展定时拉取的规则内容（只在 127.0.0.1 上提供）。"""
        return {
            "app": APP_NAME,
            "version": APP_VERSION,
            "enabled": self.browser_enabled,
            "sites": list(self.sites),
            "count": len(self.sites),
        }

    def _refresh_sites(self) -> None:
        self.listbox.delete(0, "end")
        for site in self.sites:
            self.listbox.insert("end", site)

    def _refresh_status(self) -> None:
        active = self.enabled and bool(self.sites)
        if active:
            self.status_label.configure(
                text=f"● 屏蔽生效中 · {len(self.sites)} 个网站", style="Ok.TLabel"
            )
        elif self.enabled:
            self.status_label.configure(text="○ 已开启 · 列表为空", style="Off.TLabel")
        else:
            self.status_label.configure(text="○ 屏蔽已关闭", style="Off.TLabel")

        self.toggle_btn.configure(text="关闭屏蔽" if self.enabled else "开启屏蔽")
        self.count_label.configure(text=f"共 {len(self.sites)} 个网站")

    # ---------------- hosts 操作 ----------------
    def apply(self, silent: bool = False) -> bool:
        try:
            existing = read_hosts_text().replace("\r\n", "\n").replace("\r", "\n")
            new_text = build_hosts_text(existing, self.sites, self.enabled)

            # 未开启且 hosts 里没有残留区块时无需改动文件
            if not (self.enabled and self.sites) and START_MARK not in existing:
                if not silent:
                    self._log("屏蔽未开启，hosts 无需改动")
                return True

            if new_text == existing:
                if not silent:
                    self._log("hosts 已是最新，无需写入")
                return True

            write_hosts_text(new_text)
            flush_dns()
            self._log("已更新 hosts 并刷新 DNS 缓存")
            return True
        except PermissionError:
            problem = "没有权限修改 hosts 文件，请以管理员身份运行本程序。"
        except OSError as exc:
            problem = f"修改 hosts 失败：{exc}\n请检查杀毒软件是否锁定了 hosts 文件。"
        except Exception as exc:  # noqa: BLE001 - 兜底，避免界面直接崩溃
            problem = f"发生未知错误：{exc}"

        self._log(problem)
        if not silent:
            messagebox.showerror("操作失败", problem, parent=self.root)
        return False

    # ---------------- 按钮响应 ----------------
    def add_site(self) -> None:
        raw = self.entry.get().strip()
        if not raw:
            messagebox.showinfo("提示", "请先输入要屏蔽的网站。", parent=self.root)
            self.entry.focus_set()
            return

        parts = [p for p in re.split(r"[\s,，;；]+", raw) if p]
        added: list[str] = []
        existed: list[str] = []
        invalid: list[str] = []

        for part in parts:
            try:
                domain = normalize_domain(part)
            except ValueError:
                invalid.append(part)
                continue
            if domain in self.sites or domain in added:
                existed.append(domain)
            else:
                added.append(domain)

        if not added and not existed:
            messagebox.showwarning(
                "无法添加",
                "没有识别到有效的域名。\n请检查输入，例如：example.com",
                parent=self.root,
            )
            return

        if added:
            self.sites = sorted(set(self.sites) | set(added))
            self.entry.delete(0, "end")
            self._refresh_sites()
            self._save()

            if self.enabled:
                ok = self.apply()
                if ok:
                    self._log("已添加并屏蔽：" + "、".join(added))
            else:
                self._log("已添加：" + "、".join(added) + "（屏蔽当前关闭）")
            self._refresh_status()

        if existed:
            self._log("已在列表中，跳过：" + "、".join(sorted(set(existed))))
        if invalid:
            messagebox.showwarning(
                "部分内容未能添加",
                "以下内容不是有效的域名，已跳过：\n" + "\n".join(invalid),
                parent=self.root,
            )

        self.entry.focus_set()

    def remove_selected(self) -> None:
        selection = list(self.listbox.curselection())
        if not selection:
            messagebox.showinfo("提示", "请先在列表中选择要移除的网站。", parent=self.root)
            return

        removed = [self.sites[i] for i in selection]
        for index in reversed(selection):
            del self.sites[index]

        self._refresh_sites()
        self._save()
        if self.enabled:
            self.apply()
        self._refresh_status()
        self._log("已移除：" + "、".join(removed))

    def clear_sites(self) -> None:
        if not self.sites:
            return
        if not messagebox.askyesno(
            "清空列表", f"确定要移除全部 {len(self.sites)} 个网站吗？", parent=self.root
        ):
            return

        self.sites.clear()
        self._refresh_sites()
        self._save()
        if self.enabled:
            self.apply()
        self._refresh_status()
        self._log("已清空网站列表")

    def export_browser_rules(self) -> None:
        if not self.sites:
            messagebox.showinfo(
                "提示", "网站列表为空，请先添加要屏蔽的网站。", parent=self.root
            )
            return

        text = build_filter_rules(self.sites)
        try:
            DATA_DIR.mkdir(parents=True, exist_ok=True)
            BROWSER_RULES_PATH.write_text(text, encoding="utf-8")
        except OSError as exc:
            messagebox.showerror("保存失败", f"无法写入规则文件：{exc}", parent=self.root)
            return

        copied = True
        try:
            self.root.clipboard_clear()
            self.root.clipboard_append(text)
            self.root.update_idletasks()
        except tk.TclError:
            copied = False

        self._log(f"已导出浏览器规则（{len(self.sites)} 条）：{BROWSER_RULES_PATH}")

        tips = [
            "规则文件：",
            str(BROWSER_RULES_PATH),
            "",
            "已复制到剪贴板。" if copied else "剪贴板不可用，请手动打开上面的文件复制。",
            "",
            "使用方法：",
            "1. 安装 uBlock Origin 或 AdGuard（需支持“我的过滤器 / 用户规则”）；",
            "2. 打开扩展仪表板 → 我的过滤器 / 用户规则；",
            "3. 粘贴并应用更改，然后刷新网页。",
            "",
            "规则 ||example.com^ 会同时匹配 example.com 及其所有子域名。",
        ]
        messagebox.showinfo("浏览器规则已生成", "\n".join(tips), parent=self.root)

