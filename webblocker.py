APP_NAME = "WebBlocker"
APP_VERSION = "1.1.0"

IS_WINDOWS = os.name == "nt"
CREATE_NO_WINDOW = 0x08000000 if IS_WINDOWS else 0

# ---------------------------------------------------------------------------
# 路径与常量
# ---------------------------------------------------------------------------
_default_hosts = (
    Path(os.environ.get("SystemRoot", r"C:\Windows"))
    / "System32"
    / "drivers"
    / "etc"
    / "hosts"
)
_default_data = Path(os.environ.get("APPDATA") or Path.home()) / APP_NAME

# 这两个环境变量仅用于开发调试，正常使用无需设置
HOSTS_PATH = Path(os.environ["WEBBLOCKER_HOSTS"]) if os.environ.get("WEBBLOCKER_HOSTS") else _default_hosts
DATA_DIR = Path(os.environ["WEBBLOCKER_DATA"]) if os.environ.get("WEBBLOCKER_DATA") else _default_data
CONFIG_PATH = DATA_DIR / "config.json"
BACKUP_PATH = DATA_DIR / "hosts.backup"
BROWSER_RULES_PATH = DATA_DIR / "browser-rules.txt"

START_MARK = "# >>> WebBlocker managed block - do not edit below >>>"
END_MARK = "# <<< WebBlocker managed block <<<"
BLOCK_IPS = ("0.0.0.0", "::1")

MANAGED_BLOCK_RE = re.compile(
    re.escape(START_MARK) + r".*?" + re.escape(END_MARK) + r"[ \t]*\n?",
    re.DOTALL,
)
DOMAIN_RE = re.compile(
    r"^(?=.{4,253}$)"
    r"(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+"
    r"[a-z](?:[a-z0-9-]{0,61}[a-z0-9])?$"
)


# ---------------------------------------------------------------------------
# 域名与 hosts 处理（与界面无关，方便单独测试）
# ---------------------------------------------------------------------------
def normalize_domain(raw: str) -> str:
    """把用户输入（整条网址、带 www 的域名等）规范化为裸域名。"""
    text = (raw or "").strip()
    if not text:
        raise ValueError("请输入网站地址，例如 example.com")

    if text.startswith("*."):
        text = text[2:]

    if "://" not in text:
        text = "http://" + text

    try:
        host = urlparse(text).hostname or ""
    except ValueError as exc:  # 端口非法等
        raise ValueError("无法解析这个地址") from exc

    host = host.strip().rstrip(".").lower()
    if not host:
        raise ValueError("无法从输入中识别出域名")

    # 中文域名转 punycode
    try:
        host = host.encode("idna").decode("ascii")
    except UnicodeError as exc:
        raise ValueError("域名中包含无法识别的字符") from exc

    if host.startswith("www."):
        host = host[4:]

    if not DOMAIN_RE.match(host):
        raise ValueError("这不是有效的域名（示例：example.com）")
    return host


def host_variants(domain: str) -> list[str]:
    """hosts 不支持通配符，这里覆盖主域名和最常见的子域名。"""
    return [domain, "www." + domain, "m." + domain]


def strip_managed_block(text: str) -> str:
    """删除上一次写入的受管区块，保留 hosts 中的其它内容。"""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = MANAGED_BLOCK_RE.sub("", text)

    # 标记残缺（例如用户手动删掉了结束标记）时，从开始标记起全部丢弃
    if START_MARK in text:
        text = text.split(START_MARK, 1)[0]

    lines = text.split("\n")
    while lines and not lines[-1].strip():
        lines.pop()
    return "\n".join(lines)


def build_hosts_text(existing: str, sites: list[str], enabled: bool) -> str:
    """根据网站列表生成完整的 hosts 文本（统一使用 \\n，写出时再转 CRLF）。"""
    base = strip_managed_block(existing)
    if not enabled or not sites:
        return base + "\n" if base else ""

    block = [
        START_MARK,
        "# Generated by WebBlocker. Re-save from the app instead of editing here.",
    ]
    for site in sorted(set(sites)):
        for host in host_variants(site):
            for ip in BLOCK_IPS:
                block.append(f"{ip}\t{host}")
    block.append(END_MARK)

    return (base + "\n\n" if base else "") + "\n".join(block) + "\n"


def read_hosts_text() -> str:
    """读取 hosts，使用 surrogateescape 保证非 UTF-8 的原始字节不被破坏。"""
    if not HOSTS_PATH.exists():
        return ""
    return HOSTS_PATH.read_text(encoding="utf-8", errors="surrogateescape")


def write_hosts_text(text: str) -> None:
    """备份并原子写入 hosts 文件。"""
    data = text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8", "surrogateescape")

    try:
        DATA_DIR.mkdir(parents=True, exist_ok=True)
        if HOSTS_PATH.exists():
            BACKUP_PATH.write_bytes(HOSTS_PATH.read_bytes())
    except OSError:
        pass

    # 某些系统上 hosts 带只读属性
    try:
        if HOSTS_PATH.exists() and not os.access(HOSTS_PATH, os.W_OK):
            os.chmod(HOSTS_PATH, stat.S_IWRITE | stat.S_IREAD)
    except OSError:
        pass

    tmp = HOSTS_PATH.with_name(f"hosts.{os.getpid()}.tmp")
    try:
        with open(tmp, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, HOSTS_PATH)
    except OSError:
        # 个别安全软件会拦截临时文件，退化为直接覆盖
        HOSTS_PATH.write_bytes(data)
    finally:
        try:
            if tmp.exists():
                tmp.unlink()
        except OSError:
            pass


def flush_dns() -> None:
    """刷新 Windows DNS 缓存，让新规则立即生效。"""
    if not IS_WINDOWS:
        return
    try:
        subprocess.run(
            ["ipconfig", "/flushdns"],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=CREATE_NO_WINDOW,
            timeout=15,
        )
    except Exception:
        pass


def build_filter_rules(sites: list[str]) -> str:
    """生成 uBlock Origin / AdGuard 的过滤规则。

    ||example.com^ 会同时匹配 example.com 和它的所有子域名，
    正好弥补 hosts 不支持通配符的缺点。
    """
    lines = [
        "! Title: WebBlocker 网站屏蔽",
        "! 由 WebBlocker 生成，适用于 uBlock Origin / AdGuard 的“我的过滤器 / 用户规则”",
        f"! 生成时间: {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "! 规则 ||example.com^ 会同时匹配 example.com 及其所有子域名",
        "",
    ]
    lines.extend(f"||{site}^" for site in sorted(set(sites)))
    return "\n".join(lines) + "\n"


