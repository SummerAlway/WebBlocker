"""WebBlocker —— Windows 网站屏蔽工具

原理：把要屏蔽的域名写入系统 hosts 文件，解析到 0.0.0.0 / ::1，
      这样 Chrome、Edge、Firefox 等浏览器都无法再访问这些网站。

      同时在本机启动一个只读 HTTP 接口，配套的 Chrome / Edge 扩展会自动
      读取网站列表并拦截域名下的所有子域名。

依赖：Python 3.8+ 标准库（tkinter），无需安装任何第三方库。
用法：直接双击运行，程序会自动申请管理员权限（修改 hosts 必需）。
"""

